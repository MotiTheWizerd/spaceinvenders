export type SpriteName = keyof typeof DATA;

const cache = new Map<string, HTMLCanvasElement>();

function build(rows: readonly string[], color: string): HTMLCanvasElement {
  const canvas = document.createElement('canvas');
  canvas.width = rows[0].length;
  canvas.height = rows.length;
  const ctx = canvas.getContext('2d')!;
  ctx.fillStyle = color;
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) if (row[x] === '#') ctx.fillRect(x, y, 1, 1);
  });
  return canvas;
}

/** Returns a cached, pre-rendered sprite in the given color. */
export function sprite(name: SpriteName, color: string): HTMLCanvasElement {
  const key = `${name}:${color}`;
  let canvas = cache.get(key);
  if (!canvas) {
    canvas = build(DATA[name], color);
    cache.set(key, canvas);
  }
  return canvas;
}
